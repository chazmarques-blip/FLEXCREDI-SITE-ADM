// Translation Engine
class TranslationEngine {
    constructor() {
        this.currentLang = this.getSavedLanguage() || 'en';
        this.init();
    }
    
    init() {
        // Set initial language
        this.setLanguage(this.currentLang, false);
        
        // Attach language button handlers
        document.addEventListener('DOMContentLoaded', () => {
            this.attachLanguageButtons();
            this.translatePage();
            console.log(`🌐 Translation system initialized (${this.currentLang})`);
        });
    }
    
    getSavedLanguage() {
        return localStorage.getItem('flexcredi_language') || 'en';
    }
    
    saveLanguage(lang) {
        localStorage.setItem('flexcredi_language', lang);
    }
    
    attachLanguageButtons() {
        const buttons = document.querySelectorAll('.language-btn');
        buttons.forEach(btn => {
            btn.addEventListener('click', (e) => {
                e.preventDefault();
                const lang = btn.getAttribute('data-lang');
                this.setLanguage(lang);
            });
        });
    }
    
    setLanguage(lang, translate = true) {
        if (!translations[lang]) {
            console.error(`Language '${lang}' not found`);
            return;
        }
        
        this.currentLang = lang;
        this.saveLanguage(lang);
        
        // Update active button
        document.querySelectorAll('.language-btn').forEach(btn => {
            btn.classList.remove('active');
            if (btn.getAttribute('data-lang') === lang) {
                btn.classList.add('active');
            }
        });
        
        if (translate) {
            this.translatePage();
        }
        
        console.log(`✅ Language changed to: ${lang}`);
    }
    
    translate(key) {
        const translation = translations[this.currentLang][key];
        return translation || key;
    }
    
    translatePage() {
        // Translate all elements with data-translate attribute
        const elements = document.querySelectorAll('[data-translate]');
        elements.forEach(el => {
            const key = el.getAttribute('data-translate');
            const translation = this.translate(key);
            
            // Update text content or placeholder
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                if (el.hasAttribute('placeholder')) {
                    el.setAttribute('placeholder', translation);
                }
            } else {
                // Preserve HTML structure, only update text nodes
                if (el.children.length === 0) {
                    el.textContent = translation;
                } else {
                    // For elements with children, update only direct text nodes
                    const walker = document.createTreeWalker(
                        el,
                        NodeFilter.SHOW_TEXT,
                        null,
                        false
                    );
                    
                    let node;
                    while (node = walker.nextNode()) {
                        if (node.nodeValue.trim()) {
                            node.nodeValue = translation;
                            break;
                        }
                    }
                }
            }
        });
        
        console.log(`🔄 Page translated to ${this.currentLang} (${elements.length} elements)`);
    }
}

